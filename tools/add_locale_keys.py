    p = os.path.join(ROOT, "localization", po)
    s = io.open(p, encoding="utf-8").read()
    add = ""
    for row in KEYS:
        if 'msgid "%s"' % row[0] not in s:
            add += '\nmsgid "%s"\nmsgstr "%s"\n' % (row[0], row[idx])
    if add:
        io.open(p, "w", encoding="utf-8", newline="\n").write(s.rstrip("\n") + "\n" + add)
